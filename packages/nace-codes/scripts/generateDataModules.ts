import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = join(__dirname, "..");
const dataDir = join(rootDir, "data");
const srcDir = join(rootDir, "src");
const generatedDir = join(srcDir, "generated");

mkdirSync(generatedDir, { recursive: true });

function parseTSV<T>(content: string): T[] {
	const lines = content.trim().split("\n");
	if (lines.length === 0) return [];

	const headers = lines[0]?.split("\t") ?? [];
	const data: T[] = [];

	for (let i = 1; i < lines.length; i++) {
		const line = lines[i];
		if (!line) continue;
		const values = line.split("\t");
		const obj: Record<string, string> = {};

		for (let j = 0; j < headers.length; j++) {
			const header = headers[j];
			if (!header) continue;
			let value = values[j] ?? "";
			// Remove surrounding quotes if present
			if (value.startsWith('"') && value.endsWith('"')) {
				value = value.slice(1, -1);
			}
			obj[header] = value;
		}

		data.push(obj as T);
	}

	return data;
}

function generateNACEDataModule(): void {
	console.log("Generating NACE data module...");
	
	const headingsPath = join(dataDir, "nace/NACE_Rev2.1_Heading_All_Languages.tsv");
	const structurePath = join(dataDir, "nace/NACE_Rev2.1_Structure_Explanatory_Notes_EN.tsv");
	
	const headingsContent = readFileSync(headingsPath, "utf-8");
	const structureContent = readFileSync(structurePath, "utf-8");
	
	const headings = parseTSV(headingsContent);
	const structure = parseTSV(structureContent);
	
	const moduleContent = `// Auto-generated file. Do not edit manually.
// Generated by scripts/generateDataModules.ts

import type { ParsedNACEHeading, ParsedNACEStructure } from "../types";

export const naceHeadings: ParsedNACEHeading[] = ${JSON.stringify(headings, null, "\t")};

export const naceStructure: ParsedNACEStructure[] = ${JSON.stringify(structure, null, "\t")};
`;

	writeFileSync(join(generatedDir, "naceData.ts"), moduleContent);
	console.log("✓ Generated naceData.ts");
}

function generateNACEBELDataModule(): void {
	console.log("Generating NACEBEL data module...");
	
	const nacebelPath = join(dataDir, "nacebel/codes-NACEBEL-2025.tsv");
	const nacebelContent = readFileSync(nacebelPath, "utf-8");
	const nacebel = parseTSV(nacebelContent);
	
	const headingsPath = join(dataDir, "nace/NACE_Rev2.1_Heading_All_Languages.tsv");
	const structurePath = join(dataDir, "nace/NACE_Rev2.1_Structure_Explanatory_Notes_EN.tsv");
	
	const headingsContent = readFileSync(headingsPath, "utf-8");
	const structureContent = readFileSync(structurePath, "utf-8");
	
	const headings = parseTSV(headingsContent);
	const structure = parseTSV(structureContent);
	
	const moduleContent = `// Auto-generated file. Do not edit manually.
// Generated by scripts/generateDataModules.ts

import type { ParsedNACEBEL, ParsedNACEHeading, ParsedNACEStructure } from "../types";

export const nacebelData: ParsedNACEBEL[] = ${JSON.stringify(nacebel, null, "\t")};

export const naceHeadings: ParsedNACEHeading[] = ${JSON.stringify(headings, null, "\t")};

export const naceStructure: ParsedNACEStructure[] = ${JSON.stringify(structure, null, "\t")};
`;

	writeFileSync(join(generatedDir, "nacebelData.ts"), moduleContent);
	console.log("✓ Generated nacebelData.ts");
}

function main(): void {
	console.log("Starting data module generation...\n");
	
	generateNACEDataModule();
	generateNACEBELDataModule();
	
	console.log("\n✓ Data modules generated successfully!");
	console.log("Files created in:", generatedDir);
}

main();